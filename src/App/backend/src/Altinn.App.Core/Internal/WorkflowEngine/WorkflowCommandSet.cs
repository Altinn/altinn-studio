namespace Altinn.App.Core.Internal.WorkflowEngine;

/// <summary>
/// A segment's receive half: the one step its receive workflows run — the handler answering the exchange the
/// segment ends on, whether that is a mid-pipeline one or the pipeline's terminal, named by its own item
/// index — and the item index whose stage opens the exchange that handler answers.
/// </summary>
/// <remarks>
/// The two indexes are different positions, and only <see cref="OpeningStageIndex"/> addresses the mailbox:
/// the enqueueing hop needs it to tell <c>EnqueueReceiveWorkflow</c> which carried mailbox to declare, and
/// the step beside it names the handler instead. Carried on the plan rather than looked up again, since the
/// walk that produced the step had the handler in hand.
/// </remarks>
/// <param name="Step">The receive workflow's single step.</param>
/// <param name="OpeningStageIndex">The item index whose stage's mint the receiver is enqueued against.</param>
internal sealed record MailboxReceivePlan(StepRequest Step, int OpeningStageIndex);

/// <summary>
/// One planned pipeline segment: the engine steps the workflow that runs the segment carries, and — when the
/// segment ends on an exchange — the receive half its last step enqueues instead of concluding.
/// </summary>
/// <remarks>
/// <see cref="Receive"/> non-null means the enqueuing hop must end the segment with an
/// <c>EnqueueReceiveWorkflow</c> step of its own. That last step is deliberately not planned here — its
/// labels, operation id and callback context belong to the hop doing the enqueueing, and no two hops
/// assemble them the same way.
/// </remarks>
/// <param name="Steps">The segment's steps, in execution order, with options unresolved.</param>
/// <param name="Receive">The exchange the segment ends on, or null when it ends with the conclusion.</param>
internal sealed record ServiceTaskSegmentPlan(IReadOnlyList<StepRequest> Steps, MailboxReceivePlan? Receive);

/// <summary>
/// Defines a group of commands that should be executed for a process event.
/// </summary>
internal sealed class WorkflowCommandSet
{
    private readonly List<StepRequest> _commands = [];
    private readonly List<StepRequest> _criticalPostCommitCommands = [];
    private readonly List<StepRequest> _sideEffectCommands = [];

    /// <summary>
    /// Gets the main commands for this event. SaveProcessStateToStorage will be added after these.
    /// </summary>
    public IReadOnlyList<StepRequest> Commands => _commands;

    /// <summary>
    /// Gets the post-commit commands that must complete before the transition is considered done
    /// (e.g., ExecuteServiceTask). These stay in the Main workflow and gate the next transition.
    /// </summary>
    public IReadOnlyList<StepRequest> CriticalPostCommitCommands => _criticalPostCommitCommands;

    /// <summary>
    /// Gets the non-critical, fire-and-forget post-commit commands (e.g., MovedToAltinnEvent).
    /// These run in a separate side-effects workflow that never gates the next transition.
    /// </summary>
    public IReadOnlyList<StepRequest> SideEffectCommands => _sideEffectCommands;

    /// <summary>
    /// For a mailbox-opening service task: the one step its receive workflows run, and the exchange it
    /// answers. Null for every other event.
    /// </summary>
    public MailboxReceivePlan? MailboxReceive { get; private set; }

    /// <summary>
    /// Creates command group for task start events.
    /// </summary>
    public static WorkflowCommandSet GetTaskStartSteps(TaskStartContext context)
    {
        // CleanupGeneratedFromTask runs before the hooks so that all task-start logic (including
        // app-supplied IOnTaskStartingHandler implementations) reads a clean slate, free of stale
        // elements generated by previous visits to the entering task.
        var group = new WorkflowCommandSet()
            .AddCommand(UnlockTaskData.Key)
            .AddCommand(CleanupGeneratedFromTask.Key)
            .AddCommand(OnTaskStartingHook.Key)
            .AddCommand(CommonTaskInitialization.Key, new CommonTaskInitializationPayload(context.Prefill))
            .AddCommand(StartTask.Key);

        if (context.RegisterEvents)
        {
            group.AddSideEffectCommand(MovedToAltinnEvent.Key);
        }

        if (context.ServiceTask is { } serviceTask)
        {
            ServiceTaskSegmentPlan segment = PlanSegment(serviceTask.Type, serviceTask.Pipeline);
            group.AddCriticalPostCommitSteps(segment.Steps);
            group.MailboxReceive = segment.Receive;
        }

        if (context.IsInstantiation && context.RegisterEvents)
        {
            group.AddSideEffectCommand(InstanceCreatedAltinnEvent.Key);
        }

        if (context.IsInstantiation && context.Notification is not null)
        {
            group.AddSideEffectCommand(
                NotifyInstanceOwnerOnInstantiation.Key,
                new NotifyInstanceOwnerOnInstantiationPayload(context.Notification)
            );
        }

        return group;
    }

    /// <summary>
    /// Creates command group for task end events.
    /// </summary>
    public static WorkflowCommandSet GetTaskEndSteps()
    {
        return new WorkflowCommandSet()
            .AddCommand(EndTask.Key)
            .AddCommand(CommonTaskFinalization.Key)
            .AddCommand(OnTaskEndingHook.Key)
            .AddCommand(LockTaskData.Key);
    }

    /// <summary>
    /// Creates command group for task abandon events.
    /// </summary>
    public static WorkflowCommandSet GetTaskAbandonSteps()
    {
        return new WorkflowCommandSet().AddCommand(AbandonTask.Key).AddCommand(OnTaskAbandonHook.Key);
    }

    /// <summary>
    /// Creates command group for process end events.
    /// </summary>
    public static WorkflowCommandSet GetProcessEndSteps(ProcessEndContext context)
    {
        // EndProcessLegacyHook runs post-commit because IProcessEnd.End reads instance.Process.EndEvent,
        // which is only set when the process state is persisted. This matches the old ProcessEngine behavior
        // where RunAppDefinedProcessEndHandlers ran after HandleEventsAndUpdateStorage.
        var group = new WorkflowCommandSet()
            .AddCommand(OnProcessEndingHook.Key)
            .AddCriticalPostCommitCommand(EndProcessLegacyHook.Key);

        if (context.HasAutoDeleteDataTypes)
        {
            group.AddCriticalPostCommitCommand(DeleteDataElementsIfConfigured.Key);
        }

        if (context.AutoDeleteInstanceOnProcessEnd)
        {
            group.AddCriticalPostCommitCommand(DeleteInstanceIfConfigured.Key);
        }

        if (context.RegisterEvents)
        {
            group.AddSideEffectCommand(CompletedAltinnEvent.Key);
        }

        return group;
    }

    /// <summary>
    /// Adds a command to the main sequence.
    /// </summary>
    private WorkflowCommandSet AddCommand(string commandKey, CommandRequestPayload? payload = null)
    {
        _commands.Add(CreateCommand(commandKey, payload));
        return this;
    }

    /// <summary>
    /// Adds a command that executes after the ProcessNext has been committed to storage via
    /// SaveProcessStateToStorage, and that must complete before the transition settles.
    /// </summary>
    /// <param name="commandKey">The command's registered key.</param>
    /// <param name="payload">Optional command payload.</param>
    private WorkflowCommandSet AddCriticalPostCommitCommand(string commandKey, CommandRequestPayload? payload = null)
    {
        _criticalPostCommitCommands.Add(CreateCommand(commandKey, payload));
        return this;
    }

    private WorkflowCommandSet AddCriticalPostCommitSteps(IEnumerable<StepRequest> steps)
    {
        _criticalPostCommitCommands.AddRange(steps);
        return this;
    }

    /// <summary>
    /// Adds a non-critical post-commit command that runs in the fire-and-forget side-effects workflow.
    /// </summary>
    private WorkflowCommandSet AddSideEffectCommand(string commandKey, CommandRequestPayload? payload = null)
    {
        _sideEffectCommands.Add(CreateCommand(commandKey, payload));
        return this;
    }

    /// <summary>
    /// Plans one pipeline segment: a walk over <see cref="ServiceTaskPipeline.Items"/> from where the segment
    /// starts, emitting one <c>ExecuteServiceTask</c> step per stage in composition order — each preceded by a
    /// <c>MintMailbox</c> step where the stage opens a mailbox — and ending on the first item that ends a
    /// segment. That is the next <see cref="ReplySegment"/>'s receive half, or the conclusion the list ends
    /// with: the concluding step for a <see cref="PipelineConclusion.FinalStep"/>, the receive half for a
    /// <see cref="PipelineConclusion.ReplyExchange"/>. A receive half's enqueue step is the caller's to append.
    /// </summary>
    /// <remarks>
    /// <para>
    /// <strong>Segments are the items split at each reply handler.</strong> Segment 0 rides Main; segment k
    /// rides the continuation the relay enqueues when exchange k concludes. A handler is never a step of the
    /// segment it ends: it runs on the receive workflows that segment's last step enqueues, once per message.
    /// </para>
    /// <para>
    /// Options are left unresolved: the task the steps run under is the enqueueing hop's to know, so the hop
    /// resolves them.
    /// </para>
    /// <para>
    /// A segment is planned from the pipeline as resolved at that hop, never from a projection of it carried
    /// along — the identity travelling in payloads is the item index, and the shape around it is re-derived.
    /// The expansion fixes that shape for the workflow's lifetime: a mid-flight change to the composition
    /// shifts indexes exactly as any other mid-flight process edit would.
    /// </para>
    /// <para>
    /// <strong>Frontier-never-empty is the caller's to hold, not this method's.</strong> What keeps the
    /// collection non-empty is that the step enqueueing the next receiver is the segment's <em>last</em>
    /// step, and that step is appended by the hop.
    /// </para>
    /// </remarks>
    /// <param name="serviceTaskType">The service task the steps dispatch back to.</param>
    /// <param name="pipeline">The task's pipeline, resolved at this hop.</param>
    /// <param name="afterHandlerItemIndex">
    /// The item index of the reply handler this segment follows — so the segment starts at the item after
    /// that handler. Null for segment 0, which starts at the beginning.
    /// </param>
    internal static ServiceTaskSegmentPlan PlanSegment(
        string serviceTaskType,
        ServiceTaskPipeline pipeline,
        int? afterHandlerItemIndex = null
    )
    {
        var steps = new List<StepRequest>();

        for (int index = FindSegmentStart(afterHandlerItemIndex); index < pipeline.Items.Count; index++)
        {
            switch (pipeline.Items[index])
            {
                // The two reply shapes end a segment identically: the step names the handler by its own item
                // index, and the plan carries the exchange that handler answers so the enqueueing hop knows
                // which carried mailbox to declare the receiver against.
                case ReplySegment handler:
                    return new ServiceTaskSegmentPlan(
                        steps,
                        new MailboxReceivePlan(CreateReceiveHandlerStep(serviceTaskType, index), handler.OpeningIndex)
                    );

                case PipelineConclusion.ReplyExchange exchange:
                    return new ServiceTaskSegmentPlan(
                        steps,
                        new MailboxReceivePlan(CreateReceiveHandlerStep(serviceTaskType, index), exchange.OpeningIndex)
                    );

                case PipelineConclusion.FinalStep:
                    // The concluding step carries its index like every other step, so a simple IServiceTask's
                    // one step reads "ExecuteServiceTask: 0" rather than a bare key.
                    steps.Add(
                        CreateCommand(
                            ExecuteServiceTask.Key,
                            new ExecuteServiceTaskPayload(serviceTaskType, ItemIndex: index),
                            operationId: $"{ExecuteServiceTask.Key}: {index.ToString(CultureInfo.InvariantCulture)}",
                            serviceTaskItemIndex: index
                        )
                    );
                    return new ServiceTaskSegmentPlan(steps, Receive: null);

                case ServiceTaskStage stage:
                    if (stage is ServiceTaskStage.MailboxOpening)
                    {
                        // The mint hugs the stage that sends, on both sides: the deadline clock starts here, so
                        // no earlier stage may erode it, and the stage must never send without an address, so
                        // the mint cannot come later. No stage index on the step: the mint must not inherit the
                        // stage's options, so the engine's defaults apply to what is one HTTP call.
                        steps.Add(
                            CreateCommand(
                                MintMailbox.Key,
                                new MintMailboxPayload(serviceTaskType, index),
                                operationId: $"{MintMailbox.Key}: {index.ToString(CultureInfo.InvariantCulture)}"
                            )
                        );
                    }

                    // A distinct OperationId per stage, for the engine's records and dashboards.
                    steps.Add(
                        CreateCommand(
                            ExecuteServiceTask.Key,
                            new ExecuteServiceTaskPayload(serviceTaskType, ItemIndex: index),
                            operationId: $"{ExecuteServiceTask.Key}: {index.ToString(CultureInfo.InvariantCulture)}",
                            serviceTaskItemIndex: index
                        )
                    );
                    break;

                default:
                    throw new UnreachableException(
                        $"Unknown pipeline item type: {pipeline.Items[index].GetType().Name}"
                    );
            }
        }

        // Unreachable from the runtime: a pipeline's items always end with its conclusion, and both conclusion
        // shapes return, so a walk that starts anywhere inside the list reaches one. Falling out here takes the
        // segment to start past the last item, which has exactly two causes — an afterHandlerItemIndex naming
        // the last item or beyond (a direct caller's mistake; the relay's comes from a handler dispatch just
        // ran, so an item follows it), and a Define that returned a shorter pipeline to this hop than to the
        // dispatch that produced that index, breaking its determinism contract. Named rather than swallowed:
        // planning nothing would silently drop the rest of the task.
        throw new UnreachableException(
            $"Service task '{serviceTaskType}' composes {pipeline.Items.Count} pipeline items, so a segment "
                + $"starting at index {FindSegmentStart(afterHandlerItemIndex)} reaches no conclusion. Either "
                + "the segment was planned after an item that is not a reply handler, or Define did not return "
                + "the same pipeline it returned to the dispatch that named that handler."
        );
    }

    /// <summary>
    /// Where the requested segment starts: the beginning for segment 0, and otherwise the item after the
    /// handler at <paramref name="afterHandlerItemIndex"/>.
    /// </summary>
    private static int FindSegmentStart(int? afterHandlerItemIndex) =>
        afterHandlerItemIndex is { } handler ? handler + 1 : 0;

    /// <summary>
    /// The one step a receive workflow runs: an <c>ExecuteServiceTask</c> step naming the reply handler that
    /// answers the message — a mid-pipeline <see cref="ReplySegment"/> or a
    /// <see cref="PipelineConclusion.ReplyExchange"/> — by its item index, exactly as a stage's step names the
    /// stage.
    /// </summary>
    /// <remarks>
    /// The handler's identity is fixed here, at the receiver's enqueue, and never re-derived at the hop that
    /// runs the step — a mid-flight reshape would otherwise run a different handler, or none. It travels three
    /// ways, deliberately: in the payload, which dispatch reads; in
    /// <see cref="StepRequest.ServiceTaskItemIndex"/>, which the enqueueing hop resolves the step's options by
    /// — reading that back out of the payload would mean deserializing what this hop just wrote; and in the
    /// OperationId, which is the engine's own record of the step. That OperationId carries the index for the
    /// reason every other step's does: the index <em>is</em> the identity, so a bare key would give every
    /// receive step of every exchange in a multi-exchange pipeline one telemetry name, and would quietly
    /// reintroduce "no index" as a meaning. Which exchange the step answers is not carried at all: it is read
    /// off the handler this index resolves to.
    /// </remarks>
    internal static StepRequest CreateReceiveHandlerStep(string serviceTaskType, int handlerItemIndex) =>
        CreateCommand(
            ExecuteServiceTask.Key,
            new ExecuteServiceTaskPayload(serviceTaskType, ItemIndex: handlerItemIndex),
            operationId: $"{ExecuteServiceTask.Key}: {handlerItemIndex.ToString(CultureInfo.InvariantCulture)}",
            serviceTaskItemIndex: handlerItemIndex
        );

    /// <summary>
    /// The step that ends a segment ending on an exchange: it enqueues the exchange's first receive workflow,
    /// carrying the workflow its hop pre-assembled and the item index whose stage's mailbox that receiver is
    /// declared against.
    /// </summary>
    /// <remarks>
    /// Shared by the two hops that end a segment — Main's assembly and the relay's continuation. What is
    /// <em>not</em> shared is the workflow inside it: its labels, operation id and callback context are the
    /// enqueueing hop's, and no two hops assemble them alike.
    /// </remarks>
    internal static StepRequest CreateReceiveEnqueueStep(
        WorkflowEnqueueRequest receiveEnqueueRequest,
        int openingStageIndex
    ) =>
        CreateCommand(
            EnqueueReceiveWorkflow.Key,
            new EnqueueReceiveWorkflowPayload(receiveEnqueueRequest, openingStageIndex)
        );

    private static StepRequest CreateCommand(
        string commandKey,
        CommandRequestPayload? payload = null,
        string? operationId = null,
        int? serviceTaskItemIndex = null
    )
    {
        string? serializedPayload = CommandPayloadSerializer.Serialize(payload);
        return new StepRequest
        {
            OperationId = operationId ?? commandKey,
            Command = CommandDefinition.Create(
                "app",
                new AppCommandData { CommandKey = commandKey, Payload = serializedPayload }
            ),
            CommandKey = commandKey,
            ServiceTaskItemIndex = serviceTaskItemIndex,
        };
    }
}
