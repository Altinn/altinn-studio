using System.Diagnostics;
using System.Globalization;
using Altinn.App.Core.Features.Process;
using Altinn.App.Core.Internal.WorkflowEngine.Commands;
using Altinn.App.Core.Internal.WorkflowEngine.Commands.AltinnEvents;
using Altinn.App.Core.Internal.WorkflowEngine.Commands.ProcessNext.ProcessEnd;
using Altinn.App.Core.Internal.WorkflowEngine.Commands.ProcessNext.TaskAbandon;
using Altinn.App.Core.Internal.WorkflowEngine.Commands.ProcessNext.TaskEnd;
using Altinn.App.Core.Internal.WorkflowEngine.Commands.ProcessNext.TaskStart;

namespace Altinn.App.Core.Internal.WorkflowEngine;

/// <summary>
/// One planned pipeline segment — one workflow's whole step run. A non-null
/// <see cref="ReceiveOpeningIndex"/> makes the plan a <em>receive</em> workflow: its one step is the reply
/// handler answering the exchange the stage at that index opened, so the workflow must be parked on that
/// exchange's mailbox. With it null the plan is an ordinary continuation, with no mailbox of its own.
/// Nothing here says what runs after the segment: each workflow's last step derives that when it runs, from
/// the pipeline it resolved.
/// </summary>
/// <param name="Steps">The segment's steps, in execution order, with options unresolved.</param>
/// <param name="ReceiveOpeningIndex">
/// The stage whose exchange this plan's single handler step answers, or null when the plan is not a receive
/// workflow. An index rather than a mailbox id: the id lives in the workflow state carry, and is resolved
/// from it at the hop that decides to enqueue this plan.
/// </param>
internal sealed record ServiceTaskSegmentPlan(IReadOnlyList<PlannedStep> Steps, int? ReceiveOpeningIndex);

/// <summary>
/// The steps one process event adds to a transition, in three lists: its lifecycle steps, which run before the commit
/// for a task end or abandon and after it for a task start, the steps after those in the transition's primary workflow,
/// and the steps that each get an auxiliary workflow of their own.
/// </summary>
internal sealed class WorkflowStepSet
{
    private readonly List<PlannedStep> _lifecycleSteps = [];
    private readonly List<PlannedStep> _primaryPostCommitSteps = [];
    private readonly List<PlannedStep> _auxiliarySteps = [];

    /// <summary>
    /// The lifecycle steps for this event. A task end's or abandon's run before CommitProcessState, a task start's after
    /// it.
    /// </summary>
    public IReadOnlyList<PlannedStep> LifecycleSteps => _lifecycleSteps;

    /// <summary>
    /// The steps after the commit that must complete before the transition is considered done
    /// (e.g., ExecuteServiceTask). These run in the transition's primary workflow and gate the next
    /// transition.
    /// </summary>
    public IReadOnlyList<PlannedStep> PrimaryPostCommitSteps => _primaryPostCommitSteps;

    /// <summary>
    /// The steps after the commit that run in auxiliary workflows (e.g., MovedToAltinnEvent), one
    /// workflow per step. An auxiliary workflow runs beside the process and never gates the next
    /// transition.
    /// </summary>
    public IReadOnlyList<PlannedStep> AuxiliarySteps => _auxiliarySteps;

    /// <summary>
    /// Whether this set plans a service task's steps after CommitProcessState. The service task's
    /// continuation then owns the release, so the factory adds no <see cref="ReleaseProcessingStatus"/>.
    /// </summary>
    public bool ServiceTaskFollowsCommit { get; private set; }

    /// <summary>
    /// The steps for a task start event.
    /// </summary>
    public static WorkflowStepSet GetTaskStartSteps(TaskStartContext context)
    {
        // CleanupGeneratedFromTask runs before the hooks so that all task-start logic (including
        // app-supplied IOnTaskStartingHandler implementations) reads a clean slate, free of stale
        // elements generated by previous visits to the entering task.
        var group = new WorkflowStepSet()
            .AddStep(UnlockTaskData.Key, new TaskDataLockPayload(context.TaskId))
            .AddStep(CleanupGeneratedFromTask.Key)
            .AddStep(OnTaskStartingHook.Key)
            .AddStep(CommonTaskInitialization.Key, new CommonTaskInitializationPayload(context.Prefill))
            .AddProcessTaskStages(StartTask.Key, context.StartPipeline);

        if (context.RegisterEvents)
        {
            group.AddAuxiliaryStep(MovedToAltinnEvent.Key);
        }

        if (context.ServiceTask is { } serviceTask)
        {
            group.ServiceTaskFollowsCommit = true;

            // Segment 0 always has at least one step (a handler can only answer an already-composed stage, so
            // item 0 is never one), and the primary workflow therefore always ends on a step of its own: the
            // stage whose completion starts the rest of the pipeline, or the pipeline's conclusion.
            ServiceTaskSegmentPlan segment = PlanSegment(serviceTask.Type, serviceTask.Pipeline);
            group.AddPrimaryPostCommitSteps(segment.Steps);
        }

        if (context.IsInstantiation && context.RegisterEvents)
        {
            group.AddAuxiliaryStep(InstanceCreatedAltinnEvent.Key);
        }

        if (context.IsInstantiation && context.Notification is not null)
        {
            group.AddAuxiliaryStep(
                NotifyInstanceOwnerOnInstantiation.Key,
                new NotifyInstanceOwnerOnInstantiationPayload(context.Notification)
            );
        }

        return group;
    }

    /// <summary>
    /// The steps for a task end event.
    /// </summary>
    public static WorkflowStepSet GetTaskEndSteps(string taskId, ProcessTaskPipeline endPipeline)
    {
        return new WorkflowStepSet()
            .AddProcessTaskStages(EndTask.Key, endPipeline)
            .AddStep(CommonTaskFinalization.Key)
            .AddStep(OnTaskEndingHook.Key)
            .AddStep(LockTaskData.Key, new TaskDataLockPayload(taskId));
    }

    /// <summary>
    /// The steps for a task abandon event.
    /// </summary>
    public static WorkflowStepSet GetTaskAbandonSteps(ProcessTaskPipeline abandonPipeline)
    {
        return new WorkflowStepSet()
            .AddProcessTaskStages(AbandonTask.Key, abandonPipeline)
            .AddStep(OnTaskAbandonHook.Key);
    }

    /// <summary>
    /// The steps for a process end event.
    /// </summary>
    public static WorkflowStepSet GetProcessEndSteps(ProcessEndContext context)
    {
        var group = new WorkflowStepSet()
            .AddPrimaryPostCommitStep(OnProcessEndedHook.Key)
            .AddPrimaryPostCommitStep(DeleteDataOnProcessEnd.Key);

        if (context.RegisterEvents)
        {
            group.AddAuxiliaryStep(CompletedAltinnEvent.Key);
        }

        return group;
    }

    /// <summary>
    /// Adds a lifecycle step that runs the command.
    /// </summary>
    private WorkflowStepSet AddStep(string commandKey, CommandRequestPayload? payload = null)
    {
        _lifecycleSteps.Add(CreateStep(commandKey, payload));
        return this;
    }

    /// <summary>
    /// Adds one step per stage of a process task's lifecycle pipeline, dispatched by position like service task
    /// items, so each stage saves on its own and a retry starts at the stage that failed.
    /// </summary>
    private WorkflowStepSet AddProcessTaskStages(string commandKey, ProcessTaskPipeline pipeline)
    {
        IReadOnlyList<PipelineStage.Plain> stages = pipeline.Stages;
        for (int index = 0; index < stages.Count; index++)
        {
            _lifecycleSteps.Add(
                CreateStep(
                    commandKey,
                    new ProcessTaskStagePayload(index),
                    operationId: $"{commandKey}: {index.ToString(CultureInfo.InvariantCulture)}",
                    declaredOptions: stages[index].StepOptions,
                    stepName: stages[index].DisplayName
                )
            );
        }
        return this;
    }

    /// <summary>
    /// Adds a step that runs the command after CommitProcessState has committed the transition to Storage and after
    /// any task-start steps, and that must complete before the transition settles.
    /// </summary>
    /// <param name="commandKey">The command's registered key.</param>
    /// <param name="payload">Optional command payload.</param>
    private WorkflowStepSet AddPrimaryPostCommitStep(string commandKey, CommandRequestPayload? payload = null)
    {
        _primaryPostCommitSteps.Add(CreateStep(commandKey, payload));
        return this;
    }

    private WorkflowStepSet AddPrimaryPostCommitSteps(IEnumerable<PlannedStep> steps)
    {
        _primaryPostCommitSteps.AddRange(steps);
        return this;
    }

    /// <summary>
    /// Adds a step after the commit that runs the command in its own auxiliary workflow, beside the process.
    /// </summary>
    private WorkflowStepSet AddAuxiliaryStep(string commandKey, CommandRequestPayload? payload = null)
    {
        _auxiliarySteps.Add(CreateStep(commandKey, payload));
        return this;
    }

    /// <summary>
    /// Plans one pipeline segment — one workflow's whole step run — walking the items in composition order
    /// from the one after <paramref name="afterItemIndex"/> (from the first item when it is null, which is the
    /// run the transition's primary workflow carries). A <strong>plain stage</strong> becomes one
    /// <c>ExecuteServiceTask</c> step and the walk carries on. A <strong>mailbox-opening stage</strong> becomes a
    /// <c>MintMailbox</c> step plus its own and ends the run: its work may conclude the whole task, which a
    /// step's verdict can only do while no later step of that workflow exists to run past it. A
    /// <strong>reply handler</strong> is alone in its workflow — as the run's only step when the walk starts on
    /// it, and otherwise ending the run before itself. The <strong>conclusion's</strong> step ends the run with
    /// nothing after it. Segments are therefore the items split at each reply handler and at each opening stage:
    /// segment 0 rides the transition's primary workflow, and every later segment rides the workflow its
    /// predecessor's last step enqueues — which that step derives from the pipeline when it runs, since nothing
    /// planned here is carried in a payload. Options are left unresolved.
    /// </summary>
    /// <returns>
    /// The plan, with no steps only when <paramref name="afterItemIndex"/> is the pipeline's last item: every
    /// item either ends the run or is followed by another, and the list always ends with a conclusion. The
    /// deciding hop refuses an empty plan rather than enqueue a workflow with no steps.
    /// </returns>
    internal static ServiceTaskSegmentPlan PlanSegment(
        string serviceTaskType,
        ServiceTaskPipeline pipeline,
        int? afterItemIndex = null
    )
    {
        var steps = new List<PlannedStep>();
        int firstItemIndex = afterItemIndex is { } item ? item + 1 : 0;

        for (int index = firstItemIndex; index < pipeline.Items.Count; index++)
        {
            switch (pipeline.Items[index])
            {
                // A reply handler cannot share a workflow with anything, and the two halves of that come from
                // opposite ends. The engine resolves a workflow's mailbox rendezvous for its first step only
                // (WorkflowExecutor, ProcessingOrder == 0), so a step that receives must be first; and the app
                // needs it last, because its verdict decides whether anything composed after it runs at all
                // and a step cannot cancel later steps of its own workflow. First and last means alone — so a
                // handler the walk reaches partway through ends the run before itself, and starts one of its
                // own.
                case IReplyHandlerItem when index > firstItemIndex:
                    return new ServiceTaskSegmentPlan(steps, ReceiveOpeningIndex: null);

                case IReplyHandlerItem handler:
                    steps.Add(
                        CreateItemStep(
                            serviceTaskType,
                            index,
                            pipeline.Items[index].StepOptions,
                            pipeline.Items[index].DisplayName
                        )
                    );
                    return new ServiceTaskSegmentPlan(steps, handler.OpeningIndex);

                case PipelineConclusion.Final:
                    steps.Add(
                        CreateItemStep(
                            serviceTaskType,
                            index,
                            pipeline.Items[index].StepOptions,
                            pipeline.Items[index].DisplayName
                        )
                    );
                    return new ServiceTaskSegmentPlan(steps, ReceiveOpeningIndex: null);

                case PipelineStage.MailboxOpening:
                    // The mint hugs the stage that sends, on both sides: the deadline clock starts here, and
                    // the stage must never send without an address. No stage index on the step — the mint must
                    // not inherit the stage's options.
                    steps.Add(
                        CreateStep(
                            MintMailbox.Key,
                            new MintMailboxPayload(serviceTaskType, index),
                            operationId: $"{MintMailbox.Key}: {index.ToString(CultureInfo.InvariantCulture)}"
                        )
                    );

                    steps.Add(
                        CreateItemStep(
                            serviceTaskType,
                            index,
                            pipeline.Items[index].StepOptions,
                            pipeline.Items[index].DisplayName
                        )
                    );
                    return new ServiceTaskSegmentPlan(steps, ReceiveOpeningIndex: null);

                case PipelineStage:
                    steps.Add(
                        CreateItemStep(
                            serviceTaskType,
                            index,
                            pipeline.Items[index].StepOptions,
                            pipeline.Items[index].DisplayName
                        )
                    );
                    break;

                default:
                    throw new UnreachableException(
                        $"Unknown pipeline item type: {pipeline.Items[index].GetType().Name}"
                    );
            }
        }

        return new ServiceTaskSegmentPlan(steps, ReceiveOpeningIndex: null);
    }

    /// <summary>
    /// Whether the pipeline's item at <paramref name="itemIndex"/> is an <see cref="IReplyHandlerItem"/> — the
    /// one item <see cref="PlanSegment"/> ends a run <em>before</em>, and therefore the one thing that makes
    /// an ordinary stage its workflow's last step. The same type test <see cref="PlanSegment"/>'s stop arm
    /// makes, on the interface that is the single definition of "reply handler", so the split rule and this
    /// derivation of it cannot answer differently. Read from the pipeline the executing step resolved, which
    /// is how a step knows whether it is its workflow's last without carrying an answer fixed at assembly
    /// time. False past the pipeline's end: the item that ends a run with nothing composed after it is the
    /// conclusion, and that one starts nothing.
    /// </summary>
    internal static bool ItemStartsItsOwnWorkflow(ServiceTaskPipeline pipeline, int itemIndex) =>
        pipeline.Items.ElementAtOrDefault(itemIndex) is IReplyHandlerItem;

    /// <summary>
    /// One pipeline item's engine step — a stage's, a reply handler's or the conclusion's alike. The item's
    /// index is the step's whole identity, and it travels two ways, deliberately: in the payload (dispatch
    /// reads it) and in the OperationId (the engine's own record, distinct per item for its dashboards). The
    /// item's own options ride the step as well, decided here where the pipeline is at hand, exactly as a
    /// lifecycle stage's do. Nothing about what follows the item rides here — a step's payload says what it
    /// runs, never what runs after it.
    /// </summary>
    internal static PlannedStep CreateItemStep(
        string serviceTaskType,
        int itemIndex,
        ProcessStepOptions? declaredOptions,
        string? stepName
    ) =>
        CreateStep(
            ExecuteServiceTask.Key,
            new ExecuteServiceTaskPayload(serviceTaskType, ItemIndex: itemIndex),
            operationId: $"{ExecuteServiceTask.Key}: {itemIndex.ToString(CultureInfo.InvariantCulture)}",
            declaredOptions: declaredOptions,
            stepName: stepName
        );

    /// <summary>
    /// The step label naming a pipeline step for the people following the task's progress, such as Studio's
    /// admin panel: the <see cref="PipelineItem.DisplayName"/> of the item the step runs. Display only, and absent
    /// when the item has no name: the step's identity stays its index, in the payload and the OperationId.
    /// </summary>
    internal const string StepNameLabel = "stepName";

    private static PlannedStep CreateStep(
        string commandKey,
        CommandRequestPayload? payload = null,
        string? operationId = null,
        ProcessStepOptions? declaredOptions = null,
        string? stepName = null
    ) =>
        new()
        {
            CommandKey = commandKey,
            OperationId = operationId ?? commandKey,
            Payload = payload,
            DeclaredOptions = declaredOptions,
            StepName = stepName,
        };
}
