"""Generate the studio-policy skill's lists of access packages and roles.

Reads the same Access Management endpoints as Studio's policy editor (PlatformSettings.AccessPackagesUrl and
PlatformSettings.RolesUrl in src/Designer/backend/src/Designer/appsettings.json) and writes
references/access-packages-<area group>.md and references/roles.md in agents/skills/studio-policy/. Standard library
only:

    python3 src/AI/assistant/scripts/generate_policy_references.py
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Any

ACCESS_PACKAGES_URL = "https://platform.altinn.no/accessmanagement/api/v1/meta/info/accesspackages/export"
ROLES_URL = "https://platform.altinn.no/accessmanagement/api/v1/meta/info/roles/"

SCRIPT_PATH = "src/AI/assistant/scripts/generate_policy_references.py"
REFERENCES_DIR = Path(__file__).resolve().parents[1] / "agents" / "skills" / "studio-policy" / "references"

ACCESS_PACKAGE_PREFIX = "urn:altinn:accesspackage"
ROLE_CODE_ATTRIBUTE = "urn:altinn:rolecode"

# Altinn 2 roles stop giving access at the end of 2026. The skill lists them in references/altinn2-roles.md.
ALTINN2_PROVIDER = "sys-altinn2"
# Enhetsregisteret first, since those are the roles an organization service uses. Other providers follow by name.
PROVIDER_ORDER = {"sys-ccr": 0, "sys-altinn3": 1}

# Most package descriptions end with this disclaimer, which says nothing about the package.
DISCLAIMER = re.compile(r"^Ved (?:regelverksendringer|innføring|endrede).*endringer i tilganger", re.IGNORECASE)
SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[A-ZÆØÅ])")
NORWEGIAN_LETTERS = str.maketrans({"æ": "{0", "ø": "{1", "å": "{2"})


def fetch_json(url: str) -> Any:
    request = urllib.request.Request(url, headers={"Accept": "application/json"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def sort_key(text: str) -> str:
    """Sort Norwegian text with æ, ø and å after z, in that order."""
    return text.casefold().translate(NORWEGIAN_LETTERS)


def cell(text: str | None) -> str:
    """Make text safe for one Markdown table cell."""
    return " ".join((text or "").split()).replace("|", "\\|")


def split_urn(urn: str) -> tuple[str, str]:
    """Split a subject URN into AttributeId and value at the last colon, as Studio's PolicyConverter does."""
    attribute, _, value = urn.rpartition(":")
    return attribute, value


def short_description(description: str | None) -> str:
    """The first sentence of a description, without the disclaimer about future changes."""
    sentences = [s for s in SENTENCE_END.split(" ".join((description or "").split())) if not DISCLAIMER.match(s)]
    return sentences[0] if sentences else ""


def file_slug(name: str) -> str:
    """`Særskilt` → `saerskilt`, for a file name."""
    ascii_name = name.casefold().translate(str.maketrans({"æ": "ae", "ø": "o", "å": "a"}))
    return re.sub(r"[^a-z0-9]+", "-", ascii_name).strip("-")


def render_access_packages(groups: list[dict[str, Any]]) -> dict[str, str]:
    """One file per area group, so that an agent reads only the packages for the kind of service it works on.
    Together the groups are too long for one file an agent reads whole (see .github/scripts/skills-check.py)."""
    files: dict[str, str] = {}
    for group in sorted(groups, key=lambda g: (g.get("type") != "Organisasjon", sort_key(g["name"]))):
        areas = sorted(
            (area for area in group.get("areas") or [] if area.get("packages")), key=lambda a: sort_key(a["name"])
        )
        if not areas:
            continue
        kind = str(group.get("type") or "").lower()
        lines = [
            f"<!-- Generated by {SCRIPT_PATH} from {ACCESS_PACKAGES_URL}. Do not edit. -->",
            "",
            f"# Access packages: {group['name']} ({kind})",
            "",
            f'Put the value in a subject match with `AttributeId="{ACCESS_PACKAGE_PREFIX}"`. A package marked '
            "**Not for service owners** cannot be used in a policy, and Studio does not offer it.",
            "",
            "## Contents",
            "",
            *(f"- {area['name']}" for area in areas),
        ]
        for area in areas:
            lines += ["", f"## {area['name']}", "", "| Value | Name | Description |", "|---|---|---|"]
            for package in sorted(area["packages"], key=lambda p: sort_key(p["name"])):
                attribute, value = split_urn(package["urn"])
                if attribute != ACCESS_PACKAGE_PREFIX:
                    raise ValueError(f"Unexpected access package URN: {package['urn']}")
                description = cell(short_description(package.get("description")))
                if not package.get("isResourcePolicyAvailable"):
                    description = f"**Not for service owners.** {description}"
                lines.append(f"| `{value}` | {cell(package['name'])} | {description} |")
        files[f"access-packages-{file_slug(group['name'])}.md"] = "\n".join(lines) + "\n"
    if not files:
        raise ValueError(f"No access packages in {ACCESS_PACKAGES_URL}")
    return files


def render_roles(roles: list[dict[str, Any]]) -> str:
    # Studio's policy editor offers only the roles that are available for resource policies (PolicyOptionsClient).
    offered = [
        role
        for role in roles
        if role.get("isResourcePolicyAvailable") and (role.get("provider") or {}).get("code") != ALTINN2_PROVIDER
    ]
    if not offered:
        raise ValueError(f"No roles in {ROLES_URL}")

    providers: dict[str, dict[str, Any]] = {}
    for role in offered:
        provider = role.get("provider") or {}
        if not provider.get("code"):
            raise ValueError(f"Role {role.get('code')} in {ROLES_URL} has no provider")
        providers.setdefault(provider["code"], {"name": provider.get("name") or provider["code"], "roles": []})
        providers[provider["code"]]["roles"].append(role)

    lines = [
        f"<!-- Generated by {SCRIPT_PATH} from {ROLES_URL}. Do not edit. -->",
        "",
        "# Roles",
        "",
        "The roles Studio's policy editor offers, without Altinn 2 roles. Put the value in a subject match with "
        f'`AttributeId="{ROLE_CODE_ATTRIBUTE}"`. A value with another AttributeId names it in brackets.',
    ]
    for _, provider in sorted(providers.items(), key=lambda p: (PROVIDER_ORDER.get(p[0], 99), p[1]["name"])):
        lines += ["", f"## {provider['name']}", "", "| Value | Name | Description |", "|---|---|---|"]
        for role in sorted(provider["roles"], key=lambda r: sort_key(r["name"])):
            # Studio writes the legacy URN when a role has one (PolicySubjects.tsx).
            attribute, value = split_urn(role.get("legacyUrn") or role["urn"])
            shown = f"`{value}`" if attribute == ROLE_CODE_ATTRIBUTE else f"`{value}` (`{attribute}`)"
            lines.append(f"| {shown} | {cell(role['name'])} | {cell(role.get('description'))} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    outputs = {
        **render_access_packages(fetch_json(ACCESS_PACKAGES_URL)),
        "roles.md": render_roles(fetch_json(ROLES_URL)),
    }
    REFERENCES_DIR.mkdir(parents=True, exist_ok=True)
    # An area group that no longer exists leaves no stale file behind.
    for stale in REFERENCES_DIR.glob("access-packages*.md"):
        if stale.name not in outputs:
            stale.unlink()
            print(f"Removed {stale}")
    for name, content in outputs.items():
        path = REFERENCES_DIR / name
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
